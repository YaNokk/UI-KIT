import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import {
  allExpectedStories,
  correctiveStories,
  expectedEnvironmentNames,
  storyFile
} from "./choice-control-storybook-manifest.mjs";

const repositoryRoot = resolve(import.meta.dirname, "..");
const summaryPath = resolve(
  repositoryRoot,
  ".artifacts/choice-controls-storybook-summary.json"
);
const rawReportPath = resolve(
  repositoryRoot,
  ".artifacts/choice-controls-storybook-report.json"
);
const expectedRawReport = ".artifacts/choice-controls-storybook-report.json";

function fail(message) {
  throw new Error(`Choice Control Storybook execution check failed: ${message}`);
}

function exportName(title) {
  return title.replace(/[^a-zA-Z0-9]+(.)?/g, (_match, next = "") => next.toUpperCase());
}

function exactSet(actual, expected, label) {
  if (!Array.isArray(actual)) fail(`${label} are missing.`);
  if (new Set(actual).size !== actual.length) fail(`${label} contain duplicates.`);
  const missing = expected.filter((value) => !actual.includes(value));
  const unexpected = actual.filter((value) => !expected.includes(value));
  if (missing.length || unexpected.length) {
    fail(
      `${label} differ from the manifest; missing: ${missing.join(", ") || "none"}; unexpected: ${unexpected.join(", ") || "none"}.`
    );
  }
}

function currentHead() {
  const result = spawnSync("git", ["rev-parse", "HEAD"], {
    cwd: repositoryRoot,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"]
  });
  if (result.status !== 0) fail("could not resolve current HEAD.");
  return result.stdout.trim();
}

export function validateChoiceControlStorybookEvidence(summary, rawReport, head) {
  if (!summary || typeof summary !== "object") fail("summary is missing.");
  if (!rawReport || typeof rawReport !== "object") fail("raw report is missing.");
  if (!summary.verifiedCommit) fail("verified commit is missing.");
  if (summary.verifiedCommit !== head) {
    fail(`report commit ${summary.verifiedCommit} differs from current HEAD ${head}.`);
  }
  const generatedAtTime = Date.parse(summary.generatedAt);
  if (
    typeof summary.generatedAt !== "string"
    || !Number.isFinite(generatedAtTime)
    || new Date(generatedAtTime).toISOString() !== summary.generatedAt
  ) {
    fail("generatedAt is missing or invalid.");
  }
  if (
    Number.isFinite(rawReport.startTime)
    && generatedAtTime < rawReport.startTime
  ) {
    fail("summary predates the raw report and was not generated by the same run.");
  }
  if (summary.rawReport !== expectedRawReport) {
    fail(`raw report path must be ${expectedRawReport}.`);
  }
  if (summary.storyFile !== storyFile) fail("story file differs from the manifest.");
  if (summary.sourceStoryFiles !== 1) fail("sourceStoryFiles must equal 1.");
  if (summary.logicalStories !== allExpectedStories.length) {
    fail(`logicalStories must equal ${allExpectedStories.length}.`);
  }

  exactSet(summary.environments, expectedEnvironmentNames, "environments");
  const expectedExecutions = summary.logicalStories * summary.environments.length;
  if (!Number.isInteger(summary.executions) || summary.executions <= 0) {
    fail("zero tests were executed.");
  }
  if (summary.executions !== expectedExecutions) {
    fail(`executions must equal logicalStories * environments (${expectedExecutions}).`);
  }
  if (summary.failed !== 0) fail(`${summary.failed} unexpected execution(s) failed.`);
  if (summary.skipped !== 0) fail(`${summary.skipped} execution(s) were skipped unexpectedly.`);

  if (!Array.isArray(rawReport.testResults)) fail("raw report testResults are missing.");
  if (rawReport.testResults.length !== expectedEnvironmentNames.length) {
    fail(`raw report must contain ${expectedEnvironmentNames.length} environment suites.`);
  }
  if (rawReport.numTotalTests !== summary.executions) fail("raw and normalized execution counts differ.");
  if (rawReport.numFailedTests !== summary.failed) fail("raw and normalized failure counts differ.");
  const rawSkipped = rawReport.numPendingTests + rawReport.numTodoTests;
  if (rawSkipped !== summary.skipped) fail("raw and normalized skip counts differ.");

  const runtimeIdsByStory = new Map(allExpectedStories.map((name) => [name, new Set()]));
  const allRuntimeIds = new Map();
  for (const [suiteIndex, suite] of rawReport.testResults.entries()) {
    if (!Array.isArray(suite.assertionResults)) fail(`suite ${suiteIndex + 1} has no assertions.`);
    const suiteExports = suite.assertionResults.map((assertion) => exportName(assertion.title ?? ""));
    exactSet(suiteExports, allExpectedStories, `suite ${suiteIndex + 1} stories`);
    if (!String(suite.name ?? "").replaceAll("\\", "/").endsWith(storyFile)) {
      fail(`suite ${suiteIndex + 1} source does not match the story manifest.`);
    }
    for (const assertion of suite.assertionResults) {
      const name = exportName(assertion.title ?? "");
      const storyId = assertion.meta?.storyId;
      if (!storyId) fail(`runtime story ID is missing for ${name || "unknown story"}.`);
      runtimeIdsByStory.get(name).add(storyId);
      const previousName = allRuntimeIds.get(storyId);
      if (previousName && previousName !== name) {
        fail(`runtime story ID ${storyId} is duplicated across ${previousName} and ${name}.`);
      }
      allRuntimeIds.set(storyId, name);
      if (assertion.status === "failed") fail(`runtime story ${name} failed.`);
      if (assertion.status !== "passed") fail(`runtime story ${name} was skipped.`);
    }
  }

  for (const storyName of allExpectedStories) {
    const runtimeIds = [...runtimeIdsByStory.get(storyName)];
    if (runtimeIds.length !== 1) {
      fail(`story ${storyName} does not resolve to exactly one runtime story ID.`);
    }
    const details = summary.logicalStoryDetails?.[storyName];
    if (!details || details.exportName !== storyName) fail(`logical story ${storyName} is missing.`);
    if (details.executions !== expectedEnvironmentNames.length) {
      fail(`logical story ${storyName} has an incomplete execution count.`);
    }
    exactSet(details.storyIds, runtimeIds, `logical story ${storyName} IDs`);
  }

  for (const storyName of correctiveStories) {
    const status = summary.correctiveStories?.[storyName];
    const details = summary.correctiveStoryDetails?.[storyName];
    if (!status || !details) fail(`corrective story ${storyName} is missing.`);
    if (status === "failed" || details.failed > 0) fail(`corrective story ${storyName} failed.`);
    if (status === "skipped" || details.skipped > 0) fail(`corrective story ${storyName} was skipped.`);
    if (status !== "passed" || details.status !== "passed") {
      fail(`corrective story ${storyName} has invalid status ${status}.`);
    }
    if (details.exportName !== storyName) fail(`corrective export ${storyName} is ambiguous.`);
    if (details.executions !== expectedEnvironmentNames.length) {
      fail(`corrective story ${storyName} has an incomplete execution count.`);
    }
    exactSet(details.storyIds, [...runtimeIdsByStory.get(storyName)], `corrective story ${storyName} IDs`);
    exactSet(details.environments, expectedEnvironmentNames, `corrective story ${storyName} environments`);
  }
}

function readJson(path, label) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    fail(`${label} is invalid JSON: ${error.message}`);
  }
}

function main() {
  if (!existsSync(summaryPath)) fail(`summary is missing: ${summaryPath}`);
  if (!existsSync(rawReportPath)) fail(`raw report is missing: ${rawReportPath}`);
  const summary = readJson(summaryPath, "summary");
  const rawReport = readJson(rawReportPath, "raw report");
  validateChoiceControlStorybookEvidence(summary, rawReport, currentHead());

  console.log("Choice Control Storybook execution report passed.");
  console.log(`Verified commit: ${summary.verifiedCommit}`);
  console.log(`Generated at: ${summary.generatedAt}`);
  console.log(`Executions: ${summary.executions}; skipped: ${summary.skipped}; failed: ${summary.failed}`);
  for (const storyName of correctiveStories) {
    const details = summary.correctiveStoryDetails[storyName];
    console.log(`- ${details.storyIds[0]}: ${details.status} (${details.executions})`);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) main();
